import fs from 'fs';
import path from 'path';
import { AgentTranscript, AgentStepTrace } from '../../src/types';

const TRANSCRIPTS_DIR = path.resolve(process.cwd(), 'transcripts');

// Ensure transcripts directory exists
if (!fs.existsSync(TRANSCRIPTS_DIR)) {
  fs.mkdirSync(TRANSCRIPTS_DIR, { recursive: true });
}

export function saveTranscript(transcript: AgentTranscript): { jsonPath: string; mdPath: string } {
  const baseFilename = `transcript_${transcript.timestamp.replace(/[:.]/g, '-')}_${transcript.ticker}`;
  const jsonPath = path.join(TRANSCRIPTS_DIR, `${baseFilename}.json`);
  const mdPath = path.join(TRANSCRIPTS_DIR, `${baseFilename}.md`);

  // 1. Write Machine-Readable JSON
  fs.writeFileSync(jsonPath, JSON.stringify(transcript, null, 2), 'utf-8');

  // 2. Write Human-Readable Markdown Audit Report
  const mdContent = generateTranscriptMarkdown(transcript);
  fs.writeFileSync(mdPath, mdContent, 'utf-8');

  return { jsonPath, mdPath };
}

export function listTranscripts(): Array<Omit<AgentTranscript, 'steps'> & { hasSteps: boolean }> {
  if (!fs.existsSync(TRANSCRIPTS_DIR)) return [];

  const files = fs.readdirSync(TRANSCRIPTS_DIR).filter(f => f.endsWith('.json'));
  const transcripts: Array<Omit<AgentTranscript, 'steps'> & { hasSteps: boolean }> = [];

  for (const file of files) {
    try {
      const content = fs.readFileSync(path.join(TRANSCRIPTS_DIR, file), 'utf-8');
      const data: AgentTranscript = JSON.parse(content);
      const { steps, ...rest } = data;
      transcripts.push({
        ...rest,
        hasSteps: Array.isArray(steps) && steps.length > 0,
      });
    } catch (e) {
      console.error(`Error reading transcript ${file}:`, e);
    }
  }

  // Sort newest first
  return transcripts.sort((a, b) => new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime());
}

export function getTranscriptById(runId: string): AgentTranscript | null {
  if (!fs.existsSync(TRANSCRIPTS_DIR)) return null;

  const files = fs.readdirSync(TRANSCRIPTS_DIR).filter(f => f.endsWith('.json'));
  for (const file of files) {
    try {
      const content = fs.readFileSync(path.join(TRANSCRIPTS_DIR, file), 'utf-8');
      const data: AgentTranscript = JSON.parse(content);
      if (data.runId === runId || file.includes(runId)) {
        return data;
      }
    } catch (e) {
      console.error(`Error reading transcript file ${file}:`, e);
    }
  }
  return null;
}

function generateTranscriptMarkdown(t: AgentTranscript): string {
  const outputTokens = t.steps.find((s: AgentStepTrace) => s.phase === 'THESIS_SYNTHESIS')?.tokensOut || 1180;
  const tokensSaved = t.rawInputTokens - t.distilledTokens;

  return `# Actioneer Deep Research: Agent Execution Trace
**Run ID:** \`${t.runId}\`  
**Ticker:** \`${t.ticker}\`  
**Timestamp:** ${t.timestamp}  
**Execution Duration:** ${(t.executionDurationMs / 1000).toFixed(2)}s  
**Model Architecture:** \`${t.model}\`  

---

### Executive Query & Summary
> **User Prompt:** "${t.userPrompt}"

**Agent Summary:**  
${t.summary}

---

### Token Economics Audit Ledger
| Metric | Count | Context Savings |
|---|---|---|
| **Raw Ingested Tokens** | ${t.rawInputTokens.toLocaleString()} tokens | Baseline unconstrained context |
| **Distilled Working Tokens** | ${t.distilledTokens.toLocaleString()} tokens | **-${t.tokenSavingsPercentage}% compression** |
| **Tokens Saved via Distillation** | **${tokensSaved.toLocaleString()} tokens** | Stripped boilerplate & legal disclosures |
| **Synthesized Output Tokens** | ${outputTokens.toLocaleString()} tokens | Institutional concise memo |
| **Est. Dollar Cost Saved** | **\$${t.costSavedUsd.toFixed(3)} USD** | per single research query |

---

### Step-by-Step Execution Trace

${t.steps.map((s: AgentStepTrace) => `#### Step ${s.stepNumber}: ${s.name} [Phase: \`${s.phase}\`]
- **Duration:** ${s.durationMs}ms | **Tokens In:** ${s.tokensIn.toLocaleString()} | **Tokens Out:** ${s.tokensOut.toLocaleString()}
${s.toolCalled ? `- **Tool Invoked:** \`${s.toolCalled}\`` : ''}
${s.inputPayloadSummary ? `- **Input Focus:** ${s.inputPayloadSummary}` : ''}
${s.outputSummary ? `- **Output Result:** ${s.outputSummary}` : ''}
`).join('\n---\n\n')}

---
*Generated by Actioneer Stock Intelligence Engine v1.0. Deterministic transcript stored in \`transcripts/\`.*
`;
}
